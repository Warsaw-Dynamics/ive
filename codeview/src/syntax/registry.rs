//! The languages IVE highlights: one row per grammar, plus its asset files.

use super::vendored;

/// How IVE recognises, parses and colours one language.
pub struct LanguageSpec {
    pub name: &'static str,
    /// lower-case, without the dot; matched ignoring case
    pub extensions: &'static [&'static str],
    /// exact file names, e.g. `Makefile`, or a name and any suffix, e.g. `Dockerfile.*`; win over extensions
    pub file_names: &'static [&'static str],
    /// interpreter names in a `#!` line, without version suffixes: `python` also matches `python3.12`
    pub shebangs: &'static [&'static str],
    /// lower-case names an injection may use for this language, e.g. a Markdown fence's info string
    pub aliases: &'static [&'static str],
    pub grammar: fn() -> tree_sitter::Language,
    /// IVE's highlight query; its capture names are colour key ids
    pub highlights: &'static str,
    /// IVE's injection query, with tree-sitter's `@injection.content` / `@injection.language` captures
    pub injections: Option<&'static str>,
}

macro_rules! query {
    ($($path:literal),+) => {
        concat!($(include_str!(concat!("../../../assets/queries/", $path)), "\n"),+)
    };
}

