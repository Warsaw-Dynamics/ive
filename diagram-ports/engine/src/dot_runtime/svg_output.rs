use super::{Edge, GraphKind, LayoutGraph, Model, Node, RankDir, RenderError, SubgraphModel};
use dugong::{NodeLabel, Point};

pub(super) fn render(
    model: &Model,
    graph: &LayoutGraph,
    limit: usize,
) -> Result<String, RenderError> {
    let oracle = render_oracle(model, graph, limit)?;
    Ok(validation_view(&oracle))
}

pub(super) fn render_oracle(
    model: &Model,
    graph: &LayoutGraph,
    limit: usize,
) -> Result<String, RenderError> {
    if let Some(style) = model.graph_attrs.get("style")
        && !style.is_empty()
    {
        return Err(RenderError::UnsupportedFeature(format!(
            "DOT SVG graph style {style:?}"
        )));
    }
    let rankdir = super::graph_label(&model.graph_attrs)?.rankdir;
    let mut writer = SvgWriter::new(graph, model.kind, rankdir, limit);
    writer.header(model)?;
    for (index, subgraph) in model.subgraphs.iter().enumerate() {
        writer.cluster(subgraph, index)?;
    }
    // Graphviz's default emit_view walk paints a tail, then each outgoing
    // edge's head and edge. Paint order matters where antialiased strokes cross.
    let mut painted = std::collections::HashSet::new();
    let visible_ids = model
        .nodes
        .iter()
        .filter(|node| !node.id.starts_with("__ive_dot_cluster_"))
        .enumerate()
        .map(|(index, node)| (node.id.as_str(), index))
        .collect::<std::collections::HashMap<_, _>>();
    for node in &model.nodes {
        if node.id.starts_with("__ive_dot_cluster_") {
            continue;
        }
        if painted.insert(node.id.as_str()) {
            writer.node(node, visible_index(&visible_ids, &node.id)?)?;
        }
        for (edge_index, edge) in model
            .edges
            .iter()
            .enumerate()
            .filter(|(_, edge)| edge.from == node.id)
        {
            let head_index = *model.index.get(&edge.to).ok_or_else(|| {
                RenderError::Backend(format!("DOT SVG edge head {:?} is missing", edge.to))
            })?;
            let head = &model.nodes[head_index];
            if painted.insert(head.id.as_str()) {
                writer.node(head, visible_index(&visible_ids, &head.id)?)?;
            }
            writer.edge(edge, edge_index)?;
        }
    }
    writer.push("</g>\n</svg>\n")?;
    Ok(writer.output)
}

fn visible_index(
    ids: &std::collections::HashMap<&str, usize>,
    node: &str,
) -> Result<usize, RenderError> {
    ids.get(node).copied().ok_or_else(|| {
        RenderError::Backend(format!("DOT SVG visible node {node:?} has no paint index"))
    })
}

pub(super) fn validation_view(svg: &str) -> String {
    svg.replacen("<!DOCTYPE svg PUBLIC \"-//W3C//DTD SVG 1.1//EN\"\n \"http://www.w3.org/Graphics/SVG/1.1/DTD/svg11.dtd\">\n", "", 1)
        .replacen("<!-- Generated by graphviz version 16.1.0 (20260904.0139)\n -->\n", "", 1)
}

struct SvgWriter<'a> {
    output: String,
    limit: usize,
    height: f64,
    graph: &'a LayoutGraph,
    kind: GraphKind,
    rankdir: RankDir,
}

