    #[test]
    fn should_reject_unimplemented_svg_paint_attributes() {
        // given
        let sources = [
            (
                "digraph G { bgcolor=\"red:blue\"; a; }",
                "gradient background",
            ),
            ("digraph G { a [penwidth=-2]; }", "penwidth"),
            ("digraph G { a [peripheries=3]; }", "peripheries"),
            ("digraph G { a [shape=diamond,peripheries=2]; }", "peripheries"),
            ("digraph G { a -> b [penwidth=2]; }", "penwidth"),
            ("digraph G { a -> b [style=striped]; }", "edge style"),
        ];
        let options = RenderOptions {
            language: Language::Dot,
            ..Default::default()
        };
        // when and then
        for (source, expected) in sources {
            let result = super::super::render(source, &options);
            assert!(
                matches!(result, Err(RenderError::UnsupportedFeature(message)) if message.contains(expected)),
                "{source}"
            );
        }
    }

    #[test]
    fn should_parse_production_svg_without_external_doctype() {
        // given
        let source = include_str!("../../../tools/dot-parity/fixtures/chain.dot");
        let options = RenderOptions {
            language: Language::Dot,
            ..Default::default()
        };
        // when
        let diagram = super::super::render(source, &options).unwrap();
        let tree = usvg::Tree::from_str(&diagram.svg, &usvg::Options::default());
        // then
        assert!(!diagram.svg.contains("<!DOCTYPE"));
        assert_eq!(
            diagram.svg,
            validation_view(include_str!("goldens/chain.svg"))
        );
        assert!(tree.is_ok());
    }
