#[derive(Clone, Copy)]
struct NodeStyle {
    filled: bool,
    rounded: bool,
    dash: &'static str,
    penwidth: f64,
}

impl NodeStyle {
    fn stroke_attributes(self) -> String {
        let width = if self.penwidth == 1. {
            String::new()
        } else {
            format!(" stroke-width=\"{}\"", svg_number(self.penwidth))
        };
        let dash = if self.dash.is_empty() {
            String::new()
        } else {
            format!(" stroke-dasharray=\"{}\"", self.dash)
        };
        format!("{width}{dash}")
    }

    fn needs_styled_shape(self) -> bool {
        self.rounded || self.penwidth != 1. || !self.dash.is_empty()
    }
}

#[derive(Clone, Copy)]
struct EdgeStyle {
    penwidth: f64,
    dash: &'static str,
}

