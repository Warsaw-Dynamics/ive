#!/usr/bin/env python3
"""Regenerates assets/schemes/dark.toml and light.toml from an intellij-community checkout.

Usage: tools/port_intellij_schemes.py /path/to/intellij-community

Dark is IntelliJ's New UI Dark: Default <- Default parts <- Darcula <- Darcula parts <- expUI_darkScheme.xml.
Light is New UI Light: Default <- Default parts <- expUI_lightScheme.xml.
A part is a file a plugin registers with <additionalTextAttributes scheme="..." file="..."/>; all plugin XML files of
the checkout are scanned for them. Later layers replace a key's attributes as a whole, as IntelliJ does. Only keys
in src/colors/keys/ are written.
"""
import re
import subprocess
import sys
import xml.etree.ElementTree as ElementTree
from pathlib import Path

IVE = Path(__file__).resolve().parent.parent
FIELDS = ("inherit", "foreground", "background", "bold", "italic")


def known_keys():
    tables = (IVE / "src/colors/keys").glob("*.rs")
    return {key for table in tables for key in re.findall(r'\("([A-Za-z_. ]+)", "', table.read_text())}


def scheme_parts(community):
    """{scheme name: [part file]} for every <additionalTextAttributes> outside tests, in a stable order."""
    parts = {}
    declarations = subprocess.run(["grep", "-rl", "--include=*.xml", "additionalTextAttributes ", str(community)],
                                  capture_output=True, text=True).stdout.split()
    for declaring in sorted(Path(path) for path in declarations):
        if "/test" in str(declaring):
            continue
        for scheme, file in re.findall(r'<additionalTextAttributes scheme="([^"]+)" file="([^"]+)"', declaring.read_text()):
            parts.setdefault(scheme, []).append(part_file(community, declaring, file))
    return parts


def part_file(community, declaring, file):
    """The resource `file` names, found under the module that declares it."""
    for module in declaring.parents:
        hits = sorted(path for path in module.rglob(file) if "/test" not in str(path))
        if hits:
            return hits[0]
        if module == community:
            break
    raise SystemExit(f"{declaring}: no {file}")


def attributes_of(option):
    """One <option name="KEY"> as a dict of IVE fields, or None when it sets nothing IVE reads."""
    value = option.find("value")
    if value is None:
        return {"inherit": True} if option.get("baseAttributes") else None
    entry = {}
    for field in value.findall("option"):
        name, text = field.get("name"), field.get("value")
        if text is None:
            continue  # colour-blind variants only
        if name in ("FOREGROUND", "BACKGROUND"):
            entry[name.lower()] = text.upper().rjust(6, "0")
        elif name == "FONT_TYPE":
            font = int(text)
            if font & 1:
                entry["bold"] = True
            if font & 2:
                entry["italic"] = True
    return entry


def options_of(path, scheme_name=None):
    root = ElementTree.parse(path).getroot()
    if scheme_name:
        root = next(scheme for scheme in root.findall("scheme") if scheme.get("name") == scheme_name)
    container = root.find("attributes") if root.tag == "scheme" else root
    found = {}
    for option in container.findall("option"):
        attributes = attributes_of(option)
        if attributes is not None:
            found[option.get("name")] = attributes
    return found


def layered(layers, keys):
    merged = {}
    for layer in layers:
        merged.update(layer)
    return {key: merged[key] for key in sorted(merged) if key in keys}


def toml(entries, commit):
    lines = [f"# Generated by tools/port_intellij_schemes.py from intellij-community {commit}; do not edit.", ""]
    for key, attributes in entries.items():
        lines.append(f'["{key}"]')
        for field in FIELDS:
            if field in attributes:
                value = attributes[field]
                lines.append(f"{field} = {'true' if value is True else chr(34) + value + chr(34)}")
        lines.append("")
    return "\n".join(lines)


def main(community):
    keys = known_keys()
    resources = community / "platform/platform-resources/src"
    defaults = resources / "DefaultColorSchemesManager.xml"
    parts = scheme_parts(community)
    commit = subprocess.run(["git", "-C", str(community), "rev-parse", "--short", "HEAD"], capture_output=True, text=True).stdout.strip()
    default_parts = [options_of(part) for part in parts.get("Default", [])]
    darcula_parts = [options_of(part) for part in parts.get("Darcula", [])]
    dark = [options_of(defaults, "Default"), *default_parts, options_of(defaults, "Darcula"), *darcula_parts,
            options_of(resources / "themes/expUI/expUI_darkScheme.xml")]
    light = [options_of(defaults, "Default"), *default_parts, options_of(resources / "themes/expUI/expUI_lightScheme.xml")]
    (IVE / "assets/schemes").mkdir(parents=True, exist_ok=True)
    (IVE / "assets/schemes/dark.toml").write_text(toml(layered(dark, keys), commit))
    (IVE / "assets/schemes/light.toml").write_text(toml(layered(light, keys), commit))


if __name__ == "__main__":
    main(Path(sys.argv[1]))
